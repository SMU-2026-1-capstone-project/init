package com.shadowfit.model.outbox;

/**
 * 통보 1건을 실제로 송신해본 결과. 발행기는 이 값만 보고 행의 다음 상태를 정한다.
 *
 * <p>[왜 예외가 아니라 반환값인가] 송신 실패는 이 흐름에서 <b>예외 상황이 아니라 정상적인 경우의
 * 수</b>다(AI 가 잠깐 죽는 건 설계가 전제하는 일이다). 예외로 던지면 호출자가 catch 로 분기해야 하고,
 * "재시도할 실패"와 "재시도가 무의미한 실패"를 예외 타입으로 구분하는 계층을 또 만들게 된다.
 *
 * <p>[왜 3분류인가] gRPC 에는 성공이 두 층 있다 — 전송 층(응답이 왔나)과 업무 층(그 응답이 성공인가).
 * 이 둘을 조합하면 상태가 셋이 되고, 각각 다음 행동이 다르다.
 */
public enum DispatchOutcome {

    /** 전송·업무 모두 성공. 행은 {@link OutboxStatus#SENT}. */
    SENT,

    /**
     * 지금은 실패했지만 나중엔 될 수 있다 — gRPC 오류·데드라인, 서킷 OPEN.
     * 행은 {@link OutboxStatus#PENDING} 으로 되돌리고 백오프를 건다.
     */
    RETRY,

    /**
     * 전송은 성공했는데 업무가 실패했고, <b>재시도해도 결과가 같다</b> — AI 가 세션 상태를 잃은 경우.
     * 행은 {@link OutboxStatus#FAILED}. SENT 로 찍으면 실제 결과 유실을 "전송 성공"으로 위장한다.
     */
    TERMINAL_FAILED
}
