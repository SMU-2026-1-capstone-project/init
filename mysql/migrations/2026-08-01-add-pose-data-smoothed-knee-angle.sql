--               (이슈 #79 후속 · #80 일부, docs/decisions/worst-section-rep-resolution.md §4-ㄹ)
--
-- 두 변경을 한 파일에 묶은 이유:
--   pose_data 는 파티션 테이블이라 ALTER 가 전 파티션을 다시 쓴다. 컬럼 추가와 삭제를 따로
--   적용하면 그 재구성을 두 번 한다. 지금은 pose_data 0 행이라(2026-08-01 실측) 어느 쪽이든
--   싸지만, 행이 쌓인 인스턴스에서는 한 번으로 끝내는 편이 크게 유리하다.
--
-- ⚠️ 소요 시간: 위와 같은 이유로 행 수에 비례해 오래 걸린다. 운영 중 적용은 피할 것.
-- 멱등성: MySQL 은 ADD/DROP COLUMN IF (NOT) EXISTS 를 지원하지 않는다. 재실행 시
--         1060(Duplicate column) 또는 1091(Can't DROP; check that column exists)이 나면
--         이미 적용된 것이다.

USE shadowfit;

-- ---------------------------------------------------------------------------
-- 1) smoothed_knee_angle 추가 — 프레임을 구분할 수 있는 유일한 값
-- ---------------------------------------------------------------------------
-- 왜 필요한가:
--   sync_rate 는 ai-server 가 rep 단위로 채점해 그 rep 의 모든 프레임에 복제하는 값이라
--   rep 안에서 상수다. 그래서 "이 rep 의 어느 순간이 가장 나빴나"를 sync_rate 로는 고를 수 없다.
--   그런데 joint_coordinates 는 프레임마다 다르므로, 어느 프레임을 남기느냐가 리포트에 그려질
--   자세를 결정한다. 지금은 대표 프레임을 배열 중앙(worstFrames.get(size/2))으로 고르는데
--   그건 "가장 깊었던 순간"이라는 근거가 없다.
--
-- 무엇을 담는가:
--   좌우 무릎각 평균을 최근 3프레임으로 평활한 값(도). 작을수록 깊게 앉은 것이다.
--   ai-server 가 rep 경계를 판정할 때 쓰는 값과 같다 — 그래야 "이 rep 의 바닥"과 "가장 깊은
--   프레임"이 서로 다른 근거를 갖지 않는다. 원시값이 아니라 평활값인 것은 의도적이다:
--   랜드마크가 한 프레임 튀면 그 프레임이 대표로 뽑혀 이상한 뼈대가 리포트에 그려진다.
--
-- DEFAULT 0 인 이유:
--   proto3 라 구버전 AI 는 이 필드를 보내지 않고 0 이 들어온다. rep_number 와 같은 방식으로
--   "미상"을 값 하나에 고정한다. 스쿼트 무릎각은 0 이 될 수 없으므로(세 점이 일직선이어야 180,
--   완전히 접혀도 0 이 아니다) 0 은 유효한 각도와 구분된다 — Spring 은 0 인 프레임을 대표
--   후보에서 제외하고 기존처럼 중앙 프레임으로 떨어진다.
--
-- DECIMAL(5,2) 인 이유: 각도는 0~180 이고 ai-server 가 소수 2자리로 반올림해 보낸다(round(x, 2)).
--   sync_rate 와 같은 정밀도라 컬럼 타입을 맞췄다.
--
-- 인덱스를 만들지 않는 이유:
--   이 컬럼은 WHERE 조건이 아니라 세션 하나를 읽어온 뒤 그 안에서 최소값을 고르는 데만 쓴다.
--   조회는 기존 idx_session_timestamp 로 session_id 범위가 이미 좁혀지고, 세션 하나의
--   pose_data 는 다운샘플(R=5) 후 수백 행 규모다. 쓰기 경로가 이 프로젝트의 병목이라
--   인덱스를 늘리지 않는 쪽을 택했다(rep_number 때와 같은 판단).
ALTER TABLE pose_data
    ADD COLUMN smoothed_knee_angle DECIMAL(5,2) NOT NULL DEFAULT 0.00
    AFTER sync_rate;

-- ---------------------------------------------------------------------------
-- 2) is_correct 삭제 — 읽는 곳이 없고, 있는 값과 모순된다
-- ---------------------------------------------------------------------------
-- 왜 지우는가:
--   (1) 프로덕션에서 읽는 코드가 0 이다. 엔티티 필드와 INSERT 문, 그리고 테스트만 참조했다.
--
--   (2) 파생값인데 임계값을 쓰기 시점에 굳혀 저장했다. PoseDataService 가
--       `sync_rate >= 40.0` 을 하드코딩해 넣었으므로, 임계값이 바뀌면 과거 행이 전부 틀린
--       상태가 되고 고치려면 백필이 필요하다. sync_rate 가 원본으로 남아 있으니 필요할 때
--       읽으면서 계산하면 되고, 그러면 항상 그 시점 기준으로 맞다.
--
--   (3) 같은 행 안에서 두 컬럼이 반대로 말한다. AI 는 persona 별 임계값(BEGINNER 60)으로
--       판정해 그 결과를 feedback_message 에 담아 보내는데, Spring 은 같은 질문에 40 이라는
--       다른 기준으로 두 번째 답을 저장했다. sync_rate=50 인 행은 is_correct=TRUE 이면서
--       feedback_message 는 "자세 보정 필요"다. 판정은 임계값을 아는 쪽이 한 번만 해야 한다.
--
-- 되돌리려면: ALTER TABLE pose_data ADD COLUMN is_correct BOOLEAN DEFAULT TRUE AFTER sync_rate;
--   단 과거 판정값은 복원되지 않는다(어차피 40 기준 파생값이라 sync_rate 로 재계산 가능).
ALTER TABLE pose_data
    DROP COLUMN is_correct;
